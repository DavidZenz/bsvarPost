fields <- c("analysis_type", "interval_probability", "interval_method", "scale_by", "scale_var",
            "scale_factor", "units", "source_package", "source_version", "n_draws")
ir <- array(1:6, c(1, 1, 2, 3), dimnames = list("y", "s", c("0", "1"), c("10", "30", "50")))
class(ir) <- c("PosteriorIR", "array")
draws <- tidy_irf(ir, draws = TRUE)
expect_true(all(fields %in% names(draws)))
expect_equal(draws$draw_id, rep(c("10", "30", "50"), 2))
expect_equal(draws$draw, rep(1:3, 2))
expect_true(all(is.na(draws$source_package)))
expect_true(all(draws$n_draws == 3L))
summary_tbl <- tidy_irf(ir, probability = 0.8)
expect_equal(summary_tbl$interval_probability, rep(0.8, 2))
expect_true(all(summary_tbl$interval_method == "equal_tailed"))
expect_equal(peak_response(ir)$analysis_type, "peak")
expect_equal(duration_response(ir)$units, "periods")
band <- simultaneous_irf(ir, probability = 0.8)
expect_true(all(band$analysis_type == "simultaneous"))
expect_true(all(band$interval_method == "empirical_sup_norm"))

never <- array(1, c(1, 1, 2, 3),
               dimnames = list("y", "s", c("0", "1"), c("10", "30", "50")))
class(never) <- c("PosteriorIR", "array")
no_half_life <- half_life_response(never)
no_threshold <- time_to_threshold(never, relation = "<", value = 0)
expect_equal(no_half_life$reached_prob, 0)
expect_true(is.na(no_half_life$median_half_life))
expect_equal(no_threshold$reached_prob, 0)
expect_true(is.na(no_threshold$median_horizon))
expect_true(is.na(no_threshold$interval_probability))
expect_error(time_to_threshold(replace(never, 1, NA_real_)), "finite")

hypothesis <- hypothesis_irf(ir, variables = "y", shocks = "s", horizon = 0:1, draws = TRUE)
expect_equal(hypothesis$draw_id, rep(c("10", "30", "50"), 2))
expect_true(all(hypothesis$analysis_type == "hypothesis"))
joint <- joint_hypothesis_irf(ir, variable = "y", shock = "s", horizon = 0:1,
                            compare_to = list(variable = "y", shock = "s", horizon = 0:1))
expect_equal(joint$rhs_horizon, "0,1")
expect_equal(joint$n_draws, 3L)

representative <- median_target_irf(ir)
